const fs=require('fs'), vm=require('vm'),path=require('path'),assert=require('assert');
const base=path.resolve(__dirname,'..');
const ctx={TextDecoder,DataView,ArrayBuffer,Uint8Array,console};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(base,'glb-loader.js'),'utf8'),ctx);
const b=fs.readFileSync(path.join(base,'assets/glb','survivor_sailor_rig.glb'));
const parts=ctx.RaftGLB.decodeGLB(b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength));
assert(parts.length>=35,'Character missing mesh details');
const nameSet=new Set(parts.flatMap(p=>p.path.map(n=>n.name)));
for(const joint of ['RB_Root','Hips','Spine','Head','L_Hip','R_Hip','L_Shoulder','R_Shoulder','R_Elbow','R_Wrist'])assert(nameSet.has(joint),'Missing character pivot '+joint);
const hand=parts.find(p=>p.path.some(n=>n.name==='R_Wrist'));
const start=ctx.RaftGLB.findJointTransform(hand,'R_Wrist',{});
const rotX=a=>[1,0,0,0,0,Math.cos(a),Math.sin(a),0,0,-Math.sin(a),Math.cos(a),0,0,0,0,1];
const swung=ctx.RaftGLB.findJointTransform(hand,'R_Wrist',{R_Shoulder:rotX(1.3)});
const diff=Math.hypot(swung[12]-start[12],swung[13]-start[13],swung[14]-start[14]);
assert(diff>.2,'Animated joint did not move wrist');
const neutral=ctx.RaftGLB.posedTransform(hand,{});
const moving=ctx.RaftGLB.posedTransform(hand,{R_Shoulder:rotX(1.3)});
assert(Math.hypot(moving[12]-neutral[12],moving[13]-neutral[13],moving[14]-neutral[14])>.2,'Renderer transform not affected by pose');
console.log('PASS character rig: ',parts.length,'GLB parts,',nameSet.size,'nodes, wrist moves',diff.toFixed(3),'m on throw');
