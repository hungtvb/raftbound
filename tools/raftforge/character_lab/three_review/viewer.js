import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {OrbitControls} from 'three/addons/controls/OrbitControls.js';

/* Isolated browser acceptance rig, not an invisible replacement in RAFTBOUND.
   It plays the literal glTF clips generated by Blender from game/cast-motion.js.
   The shipping WebGL2 game still uses a different 17-bone skinning contract. */
const canvas=document.querySelector('#view');
const status=document.querySelector('#status');
const select=document.querySelector('#clip');
const pause=document.querySelector('#pause');
const scene=new THREE.Scene();
scene.background=new THREE.Color('#193b4b');
scene.fog=new THREE.Fog('#193b4b',14,25);
const camera=new THREE.PerspectiveCamera(38,1,0.05,100);
camera.position.set(3.4,2.1,4.6);
const renderer=new THREE.WebGLRenderer({canvas,antialias:true,alpha:false,
  powerPreference:'high-performance',preserveDrawingBuffer:true});
renderer.setPixelRatio(Math.min(window.devicePixelRatio||1,2));
renderer.outputColorSpace=THREE.SRGBColorSpace;
renderer.toneMapping=THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure=1.35;
renderer.shadowMap.enabled=false;
scene.add(new THREE.HemisphereLight('#d2ecff','#68767a',2.1));
const key=new THREE.DirectionalLight('#ffe9cc',3.5);
key.position.set(4,8,6);scene.add(key);
const fill=new THREE.DirectionalLight('#9ad7ff',1.4);
fill.position.set(-5,3,-4);scene.add(fill);
const floor=new THREE.Mesh(
  new THREE.CylinderGeometry(1.5,1.6,.08,80),
  new THREE.MeshStandardMaterial({color:'#285e68',roughness:.9}));
floor.position.y=-.065;scene.add(floor);
const grid=new THREE.GridHelper(7,18,'#397c82','#244f58');
grid.position.y=-.021;scene.add(grid);
const controls=new OrbitControls(camera,canvas);
controls.enableDamping=true;
controls.target.set(0,.97,0);
controls.minDistance=2;controls.maxDistance=9;
controls.update();
let clock=new THREE.Clock(),mixer=null,clips={},avatar=null,bones=[],active=null;
let stopped=false,elapsed=0,triangles=0,meshes=0,skinMeshes=0;
const API={ready:false,error:null,clips:[],bones:0,skinnedMeshes:0,triangles:0,frame:0,
  setMotion(name,time=0){
    if(!mixer)throw Error('Model not loaded');
    if(!clips[name])throw Error('Missing glTF clip '+name);
    if(active)active.stop();
    mixer.stopAllAction();
    active=mixer.clipAction(clips[name]);
    active.reset().setEffectiveWeight(1);
    active.setLoop(name==='cast'?THREE.LoopOnce:THREE.LoopRepeat,Infinity);
    active.clampWhenFinished=true;
    active.play();elapsed=0;
    this.seek(time);select.value=name;
    return this.poseSignature();
  },
  seek(t){
    if(!active)throw Error('No motion playing');
    const duration=active.getClip().duration;
    elapsed=Math.max(0,Math.min(t,duration-.00001));
    // Set animation state deterministically for CI screenshot and joint metrics.
    mixer.setTime(elapsed);avatar.updateMatrixWorld(true);
    renderer.render(scene,camera);
  },
  pause(){stopped=true;clock.stop();},
  resume(){stopped=false;clock.start();},
  poseSignature(){
    if(!avatar)return [];
    return bones.filter(b=>/spine|upperarm|lowerarm|thigh|calf|head|pelvis/i.test(b.name))
      .flatMap(b=>[b.name, ...b.quaternion.toArray().map(v=>Math.round(v*10000)/10000)]);
  }
};
window.__raftReview=API;
function resize(){
  const w=Math.max(canvas.clientWidth,10),h=Math.max(canvas.clientHeight,10);
  renderer.setSize(w,h,false);
  camera.aspect=w/h;camera.updateProjectionMatrix();
}
window.addEventListener('resize',resize);
resize();
select.addEventListener('change',()=>API.setMotion(select.value,0));
pause.addEventListener('click',()=>{
  if(stopped){API.resume();pause.textContent='Pause'}
  else{API.pause();pause.textContent='Play'}
});
const modelUrl=new URLSearchParams(window.location.search).get('asset')||
  '/qa-character-a14/sailor-animated.glb';
new GLTFLoader().load(modelUrl,(gltf)=>{
  try{
    avatar=gltf.scene;
    avatar.traverse(node=>{
      if(node.isMesh){
        meshes++;triangles+=(node.geometry.index?
          node.geometry.index.count:node.geometry.attributes.position.count)/3;
        if(node.isSkinnedMesh){skinMeshes++;bones.push(...node.skeleton.bones);}
        if(node.material){
          const materials=Array.isArray(node.material)?node.material:[node.material];
          for(const material of materials){material.side=THREE.DoubleSide}
        }
      }
    });
    bones=[...new Set(bones)];
    if(bones.length<60||skinMeshes<4)throw Error(
      `Incomplete animated rig: ${bones.length} bones, ${skinMeshes} skinned meshes`);
    for(const clip of gltf.animations){
      const name=clip.name.toLowerCase();
      for(const mode of ['idle','walk','cast']){
        if(name.includes(mode))clips[mode]=clip;
      }
    }
    if(['idle','walk','cast'].some(n=>!clips[n]))throw Error(
      'Missing actual glTF clips: '+gltf.animations.map(c=>c.name).join(', '));
    mixer=new THREE.AnimationMixer(avatar);
    scene.add(avatar);
    API.ready=true;API.clips=gltf.animations.map(c=>({name:c.name,duration:c.duration,tracks:c.tracks.length}));
    API.bones=bones.length;API.skinnedMeshes=skinMeshes;API.triangles=Math.round(triangles);
    status.textContent=`${bones.length} bones · ${skinMeshes} skinned meshes · ${Math.round(triangles)} triangles`;
    API.setMotion('idle',0);
    console.info('RAFTFORGE THREE REAL GLTF RIG READY',API.clips);
  }catch(err){fail(err)}
},undefined,fail);
function fail(err){API.error=err?.message||String(err);status.textContent=API.error;console.error(err);}
function frame(){
  requestAnimationFrame(frame);
  const delta=Math.min(clock.getDelta(),.05);
  if(mixer&&!stopped){
    elapsed+=delta;
    if(active?.getClip().name?.toLowerCase().includes('cast'))
      elapsed=Math.min(elapsed,active.getClip().duration);
    mixer.update(delta);
  }
  controls.update();
  renderer.render(scene,camera);API.frame++;
}
frame();
